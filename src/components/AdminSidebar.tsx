export function AdminSidebar({ userName }: { userName: string }) {
  const { t } = useI18n();
  const pathname = usePathname();
  const [mobileOpen, setMobileOpen] = useState(false);

  useEffect(() => {
    setMobileOpen(false);
  }, [pathname]);

  const isActive = (href: string) => {
    if (href === "/admin") return pathname === "/admin";
    return pathname.startsWith(href);
  };

  const sidebarContent = (
    <div className="flex h-full flex-col bg-admin-sidebar-bg">
      <div className="px-5 py-5">
        <span className="text-lg font-bold text-admin-text">{t("wmsAdmin")}</span>
      </div>

      <nav className="flex-1 space-y-1 px-3">
        {NAV_ITEMS.map((item) => {
          const active = isActive(item.href);
          return (
            <Link
              key={item.key}
              href={item.href}
              className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
                active
                  ? "bg-admin-accent/15 text-admin-accent"
                  : "text-admin-text-secondary hover:bg-admin-surface-hover hover:text-admin-text"
              }`}
            >
              {item.icon}
              {t(item.key)}
            </Link>
          );
        })}
      </nav>

      <div className="border-t border-admin-border px-4 py-4">
        <div className="mb-3 flex items-center justify-between">
          <span className="truncate text-sm text-admin-text-secondary">{userName}</span>
          <LangToggle />
        </div>
        <LogoutButton />
      </div>
    </div>
  );

  return (
    <>
      {/* Mobile top bar */}
      <div className="fixed left-0 right-0 top-0 z-30 flex items-center gap-3 bg-admin-sidebar-bg px-4 py-3 md:hidden">
        <button
          type="button"
          onClick={() => setMobileOpen((o) => !o)}
          className="text-admin-text-secondary hover:text-admin-text"
        >
          <svg className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M3.75 6.75h16.5M3.75 12h16.5m-16.5 5.25h16.5" />
          </svg>
        </button>
        <span className="text-sm font-bold text-admin-text">{t("wmsAdmin")}</span>
      </div>

      {/* Desktop sidebar */}
      <aside className="hidden w-60 shrink-0 md:block">
        {sidebarContent}
      </aside>

      {/* Mobile slide-over */}
      {mobileOpen && (
        <div className="fixed inset-0 z-40 md:hidden">
          <div
            className="fixed inset-0 bg-black/50"
            onClick={() => setMobileOpen(false)}
          />
          <aside className="fixed left-0 top-0 h-full w-60">
            {sidebarContent}
          </aside>
        </div>
      )}
    </>
  );
}
